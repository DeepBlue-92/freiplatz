/**
 * Extracts pure language bundles ({ de: { ... }, en: { ... } }) from the unified TRANSLATIONS dictionary.
 */
function extractBundle(dict: any, lang: "de" | "en"): any {
  const result: any = {};
  for (const [key, value] of Object.entries(dict)) {
    if (value && typeof value === "object") {
      if ("de" in value && "en" in value) {
        result[key] = value[lang];
      } else {
        result[key] = extractBundle(value, lang);
      }
    }
  }
  return result;
}

